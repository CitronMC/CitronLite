#!/usr/bin/env python3
"""Regenerate include/citron/font_data.h from the TTFs in assets/fonts/.

    python tools/embed_fonts.py

The fonts are compiled in so the single executable needs nothing beside it. Run this after
replacing a TTF.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
FONTS = os.path.join(ROOT, "assets", "fonts")
DEST = os.path.join(ROOT, "include", "citron", "font_data.h")

FACES = [
    ("kHankenRegular", "HankenGrotesk-Regular.ttf"),
    ("kHankenMedium", "HankenGrotesk-Medium.ttf"),
    ("kHankenSemiBold", "HankenGrotesk-SemiBold.ttf"),
    ("kSchibstedSemiBold", "SchibstedGrotesk-SemiBold.ttf"),
    ("kSchibstedBold", "SchibstedGrotesk-Bold.ttf"),
    ("kMonoMedium", "JetBrainsMono-Medium.ttf"),
]


def main() -> int:
    out = [
        "// Generated by tools/embed_fonts.py from assets/fonts, each font under its OFL file there.",
        "#pragma once",
        "",
        "namespace citron::fontdata {",
        "",
    ]
    for symbol, name in FACES:
        path = os.path.join(FONTS, name)
        if not os.path.exists(path):
            print("missing %s" % path, file=sys.stderr)
            return 1
        with open(path, "rb") as handle:
            data = handle.read()
        if data[:4] not in (b"\x00\x01\x00\x00", b"true", b"OTTO"):
            print("%s is not a TrueType or OpenType font" % path, file=sys.stderr)
            return 1
        out.append("inline constexpr unsigned char %s[] = {" % symbol)
        for at in range(0, len(data), 20):
            out.append("    " + "".join("0x%02X," % b for b in data[at:at + 20]))
        out.append("};")
        out.append("")
    out.append("}  // namespace citron::fontdata")
    out.append("")
    with open(DEST, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(out))
    print("wrote %s" % DEST)
    return 0


sys.exit(main())
